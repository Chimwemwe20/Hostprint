#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_everything_untrusted() {
        assert_eq!(
            esc("<script>alert('x')</script> & \"y\""),
            "&lt;script&gt;alert(&#39;x&#39;)&lt;/script&gt; &amp; &quot;y&quot;"
        );
    }

    #[test]
    fn bars_change_colour_with_usage() {
        assert!(bar(0.5).starts_with("<span class=\"bar\">"));
        assert!(bar(0.75).contains("bar warn"));
        assert!(bar(0.95).contains("bar crit"));
        assert!(bar(1.7).contains("width:100%"));
    }
}
